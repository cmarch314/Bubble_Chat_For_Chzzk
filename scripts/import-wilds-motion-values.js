#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const inputPath = process.argv[2] || path.join(root, 'game_extracts', 'tools', 'mhwilds_motion_values_1.040.ndjson');
const jsonPath = process.argv[3] || path.join(root, 'data', 'hunt', 'wilds-motion-values.json');
const jsPath = process.argv[4] || path.join(root, 'js', 'effects', 'hunt', 'data', 'WildsMotionValues.generated.js');

const WEAPONS = Object.freeze({
    GS: 'great_sword', LS: 'long_sword', SnS: 'sword_shield', DB: 'dual_blades', Hammer: 'hammer', HH: 'hunting_horn',
    Lance: 'lance', GL: 'gunlance', 'GL Shelling': 'gunlance_shelling', SA: 'switch_axe', CB: 'charge_blade', IG: 'insect_glaive',
    LBG: 'light_bowgun', HBG: 'heavy_bowgun', Bow: 'bow'
});

function cleanRow(row) {
    const result = [...row];
    while (result.length && result[result.length - 1] == null) result.pop();
    return result;
}

function slug(value) {
    return String(value || '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

function numericHits(value) {
    if (typeof value === 'number' && Number.isFinite(value)) return [value];
    if (typeof value !== 'string' || /\?/.test(value)) return [];
    const numbers = [...value.matchAll(/\d+(?:\.\d+)?/g)].map(match => Number(match[0]));
    return numbers.every(Number.isFinite) ? numbers : [];
}

function standardRows(table, weaponId) {
    const rows = table.values || [];
    const headerIndex = rows.findIndex(row => String(row?.[0] || '').trim().toLowerCase() === 'attack');
    if (headerIndex < 0) return [];
    const headers = rows[headerIndex].map(value => String(value || '').trim());
    return rows.slice(headerIndex + 1).map((raw, index) => {
        const row = cleanRow(raw);
        const name = String(row[0] || '').trim();
        const hits = numericHits(row[1]);
        if (!name || !hits.length) return null;
        const properties = {};
        headers.forEach((header, column) => {
            if (column > 1 && header && row[column] != null) properties[header] = row[column];
        });
        return {
            id: `${weaponId}.${slug(name)}`,
            name,
            motionValue: row[1],
            motionValueHits: hits,
            motionValueTotal: Number(hits.reduce((sum, hit) => sum + hit, 0).toFixed(4)),
            properties,
            sourceRow: headerIndex + index + 2,
            motionTimeSeconds: null,
            timingEvidence: 'unresolved'
        };
    }).filter(Boolean);
}

function bowgunRows(table, weaponId) {
    const rows = table.values || [];
    return rows.slice(2).map((raw, index) => {
        const row = cleanRow(raw);
        const name = String(row[0] || '').trim();
        const hits = numericHits(row[1]);
        if (!name || !hits.length) return null;
        return {
            id: `${weaponId}.${slug(name)}`,
            name,
            motionValue: row[1],
            motionValueHits: hits,
            motionValueTotal: Number(hits.reduce((sum, hit) => sum + hit, 0).toFixed(4)),
            properties: { rawColumns: row.slice(1) },
            sourceRow: index + 3,
            motionTimeSeconds: null,
            timingEvidence: 'unresolved'
        };
    }).filter(Boolean);
}

function main() {
    if (!fs.existsSync(inputPath)) throw new Error(`Wilds motion-value inspection is missing: ${inputPath}`);
    const tables = fs.readFileSync(inputPath, 'utf8').trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
    const weapons = {};
    for (const table of tables) {
        const weaponId = WEAPONS[table.sheet];
        if (!weaponId) continue;
        weapons[weaponId] = ['LBG', 'HBG'].includes(table.sheet) ? bowgunRows(table, weaponId) : standardRows(table, weaponId);
    }
    const data = {
        version: 1,
        game: 'Monster Hunter Wilds',
        gameVersion: '1.040.0',
        source: {
            title: 'MH Wilds Motion Values (1.040.0 update)',
            workbookId: '1F_bOwQT6A6mFtCN7WCetnZDrmvLYu-ne4y97IsG6Fkk',
            url: 'https://docs.google.com/spreadsheets/d/1F_bOwQT6A6mFtCN7WCetnZDrmvLYu-ne4y97IsG6Fkk/edit'
        },
        timingPolicy: 'motionTimeSeconds remains null until measured from game animation/FSM data or verified frame footage',
        weapons
    };
    fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
    fs.mkdirSync(path.dirname(jsPath), { recursive: true });
    fs.writeFileSync(jsonPath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
    fs.writeFileSync(jsPath,
        `'use strict';\n\n// Generated by scripts/import-wilds-motion-values.js. Do not hand-edit.\nconst HUNT_WILDS_MOTION_VALUES = ${JSON.stringify(data)};\n\nif (typeof module !== 'undefined' && module.exports) module.exports = HUNT_WILDS_MOTION_VALUES;\nelse window.HUNT_WILDS_MOTION_VALUES = HUNT_WILDS_MOTION_VALUES;\n`,
        'utf8'
    );
    const count = Object.values(weapons).reduce((sum, rows) => sum + rows.length, 0);
    console.log(`[hunt-motion] imported ${count} Wilds motion-value rows -> ${jsonPath}`);
}

if (require.main === module) main();
module.exports = { numericHits, standardRows, bowgunRows };
