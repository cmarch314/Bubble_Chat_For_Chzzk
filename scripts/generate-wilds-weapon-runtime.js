const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'data', 'hunt', 'wilds-game-reference.json');
const outputPath = path.join(root, 'js', 'effects', 'hunt', 'data', 'WildsWeaponInstances.generated.js');
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
const mergedWeaponDir = path.join(root, 'game_extracts', 'tools', 'mhdb-wilds-data', 'output', 'merged', 'weapons');
const koreanByEnglish = new Map();
const collectLocalizedNames = value => {
    if (!value || typeof value !== 'object') return;
    const names = value.names || value.name;
    if (names?.en && names?.ko) koreanByEnglish.set(String(names.en), String(names.ko));
    Object.values(value).forEach(collectLocalizedNames);
};
if (fs.existsSync(mergedWeaponDir)) {
    fs.readdirSync(mergedWeaponDir).filter(file => file.endsWith('.json')).forEach(file => {
        collectLocalizedNames(JSON.parse(fs.readFileSync(path.join(mergedWeaponDir, file), 'utf8')));
    });
}
const keep = weapon => ({
    id: Number(weapon.id),
    name: String(weapon.name || ''),
    nameKo: koreanByEnglish.get(String(weapon.name || '')) || null,
    kind: String(weapon.kind || '').replace(/-/g, '_'),
    rarity: Number(weapon.rarity || 0),
    raw: Number(weapon.damage?.raw || 0),
    affinity: Number(weapon.affinity || 0),
    element: (weapon.specials || []).find(special => special?.kind === 'element' && !special.hidden)?.element || null,
    sharpness: weapon.sharpness ? Object.fromEntries(
        ['red', 'orange', 'yellow', 'green', 'blue', 'white', 'purple'].map(color => [color, Number(weapon.sharpness[color] || 0)])
    ) : null,
    evidence: weapon.evidence || 'wilds-game-files-via-mhdb'
});
const weapons = (source.finalWeapons || []).filter(weapon => weapon.finalTreeNode !== false).map(keep);
const missingKorean = weapons.filter(weapon => !weapon.nameKo);
if (missingKorean.length) throw new Error(`Missing official Korean names for ${missingKorean.length} weapons: ${missingKorean.slice(0, 5).map(item => item.name).join(', ')}`);
const text = `// Generated by scripts/generate-wilds-weapon-runtime.js. Do not edit by hand.\n`+
    `const HUNT_WILDS_WEAPON_INSTANCES = ${JSON.stringify(weapons)};\n`+
    `if (typeof module !== 'undefined' && module.exports) module.exports = HUNT_WILDS_WEAPON_INSTANCES;\n`+
    `else window.HUNT_WILDS_WEAPON_INSTANCES = HUNT_WILDS_WEAPON_INSTANCES;\n`;
fs.writeFileSync(outputPath, text, 'utf8');
console.log(`[wilds-weapons] wrote ${weapons.length} final weapons to ${path.relative(root, outputPath)}`);
