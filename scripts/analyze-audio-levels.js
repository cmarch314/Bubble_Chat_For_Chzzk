const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const projectRoot = path.resolve(__dirname, '..');
const outputPath = path.join(projectRoot, 'js', 'audio-levels.generated.js');
const roots = ['SFX', 'BGM', 'MonsterHunter_Soundtracks', 'Video', 'AI CMC'];
const extensions = new Set(['.mp3', '.wav', '.ogg', '.m4a', '.aac', '.flac', '.mp4', '.webm']);
const concurrencyArg = process.argv.find(arg => arg.startsWith('--concurrency='));
const concurrency = Math.max(1, Number(concurrencyArg?.split('=')[1]) || 4);
const CHAT_VOICE_POLICY_VERSION = 2;

function collectFiles(directory) {
    if (!fs.existsSync(directory)) return [];
    const files = [];
    const stack = [directory];
    while (stack.length > 0) {
        const current = stack.pop();
        for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
            const fullPath = path.join(current, entry.name);
            if (entry.isDirectory()) stack.push(fullPath);
            else if (extensions.has(path.extname(entry.name).toLowerCase())) files.push(fullPath);
        }
    }
    return files;
}

function parseExisting() {
    if (!fs.existsSync(outputPath)) return {};
    const source = fs.readFileSync(outputPath, 'utf8');
    const marker = 'window.HIVE_AUDIO_LEVELS = ';
    const start = source.indexOf(marker);
    if (start === -1) return {};
    const jsonStart = start + marker.length;
    const jsonEnd = source.lastIndexOf(';');
    if (jsonEnd <= jsonStart) return {};
    try { return JSON.parse(source.slice(jsonStart, jsonEnd)); } catch (error) { return {}; }
}

function writeOutput(entries) {
    const ordered = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
    const source = [
        '// Generated by scripts/analyze-audio-levels.js. Originals are never modified.',
        `window.HIVE_AUDIO_LEVELS = ${JSON.stringify(ordered, null, 2)};`,
        ''
    ].join('\n');
    fs.writeFileSync(outputPath, source, 'utf8');
}

function relativePath(filePath) {
    return path.relative(projectRoot, filePath).replace(/\\/g, '/');
}

function durationFromLog(log) {
    const match = log.match(/Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)/);
    if (!match) return 0;
    return Number(match[1]) * 3600 + Number(match[2]) * 60 + Number(match[3]);
}

function categoryFor(relative, duration) {
    if (relative.startsWith('BGM/')) return 'bgm';
    if (relative.startsWith('Video/') || relative.startsWith('AI CMC/')) return 'visual';
    if (relative.startsWith('SFX/Add/') || relative.startsWith('SFX/Chzzk_Signatures/')) return 'chat_voice';
    if (relative.startsWith('MonsterHunter_Soundtracks/') && duration > 30) return 'bgm';
    return 'sfx';
}

function targetFor(category, duration = 0) {
    if (category === 'bgm') return -22;
    if (category === 'visual') return -18;
    if (category === 'chat_voice') return duration < 0.4 ? -20 : -18;
    return -16;
}

function runFfmpeg(args) {
    return new Promise((resolve, reject) => {
        const child = spawn('ffmpeg', args, { windowsHide: true });
        let log = '';
        child.stderr.setEncoding('utf8');
        child.stderr.on('data', chunk => { log += chunk; });
        child.on('error', reject);
        child.on('close', code => resolve({ code, log }));
    });
}

function buildEntry(filePath, relative, category, duration, measurement) {
    const stat = fs.statSync(filePath);
    return {
        relative,
        entry: {
            category,
            ...measurement,
            duration: Number(duration.toFixed(3)),
            bytes: stat.size,
            mtimeMs: Math.round(stat.mtimeMs)
        }
    };
}

async function analyze(filePath) {
    const loudness = await runFfmpeg([
        '-nostdin', '-hide_banner', '-nostats', '-i', filePath,
        '-af', 'loudnorm=I=-16:TP=-1:LRA=11:print_format=json',
        '-f', 'null', 'NUL'
    ]);
    if (loudness.code !== 0) throw new Error(`ffmpeg measurement failed (${loudness.code})`);

    const duration = durationFromLog(loudness.log);
    const relative = relativePath(filePath);
    const category = categoryFor(relative, duration);
    const policy = category === 'chat_voice' ? { policyVersion: CHAT_VOICE_POLICY_VERSION } : {};
    const jsonStart = loudness.log.lastIndexOf('{');
    const jsonEnd = loudness.log.lastIndexOf('}');
    if (jsonStart !== -1 && jsonEnd > jsonStart) {
        const measurement = JSON.parse(loudness.log.slice(jsonStart, jsonEnd + 1));
        const inputLufs = Number(measurement.input_i);
        const truePeakDb = Number(measurement.input_tp);
        if (Number.isFinite(inputLufs) && Number.isFinite(truePeakDb)) {
            const desiredGain = targetFor(category, duration) - inputLufs;
            const peakLimitedGain = -1 - truePeakDb;
            const gainDb = Math.max(-18, Math.min(12, desiredGain, peakLimitedGain));
            return buildEntry(filePath, relative, category, duration, {
                inputLufs: Number(inputLufs.toFixed(2)),
                truePeakDb: Number(truePeakDb.toFixed(2)),
                gainDb: Number(gainDb.toFixed(2)),
                measurement: 'loudnorm',
                ...policy
            });
        }
    }

    // EBU R128 cannot produce integrated LUFS for very short or silent clips.
    // Fall back to mean/peak measurement so these assets still get deterministic staging.
    const volume = await runFfmpeg([
        '-nostdin', '-hide_banner', '-nostats', '-i', filePath,
        '-af', 'volumedetect', '-f', 'null', 'NUL'
    ]);
    if (volume.code !== 0) throw new Error(`ffmpeg fallback measurement failed (${volume.code})`);
    const meanMatch = volume.log.match(/mean_volume:\s*(-?(?:\d+(?:\.\d+)?|inf))\s*dB/i);
    const peakMatch = volume.log.match(/max_volume:\s*(-?(?:\d+(?:\.\d+)?|inf))\s*dB/i);
    const meanDb = Number(meanMatch?.[1]);
    const truePeakDb = Number(peakMatch?.[1]);

    if (!Number.isFinite(meanDb) || !Number.isFinite(truePeakDb) || truePeakDb <= -90) {
        return buildEntry(filePath, relative, category, duration, {
            inputLufs: null,
            truePeakDb: Number.isFinite(truePeakDb) ? Number(truePeakDb.toFixed(2)) : null,
            gainDb: 0,
            measurement: 'silence',
            silent: true,
            ...policy
        });
    }

    const desiredGain = targetFor(category, duration) - meanDb;
    const peakLimitedGain = -1 - truePeakDb;
    const gainDb = Math.max(-18, Math.min(12, desiredGain, peakLimitedGain));
    return buildEntry(filePath, relative, category, duration, {
        inputLufs: null,
        meanDb: Number(meanDb.toFixed(2)),
        truePeakDb: Number(truePeakDb.toFixed(2)),
        gainDb: Number(gainDb.toFixed(2)),
        measurement: 'volume-fallback',
        ...policy
    });
}

async function main() {
    const files = roots.flatMap(root => collectFiles(path.join(projectRoot, root)));
    const entries = parseExisting();
    const pending = files.filter(filePath => {
        const relative = relativePath(filePath);
        const existing = entries[relative];
        const stat = fs.statSync(filePath);
        const isChatVoice = relative.startsWith('SFX/Add/') || relative.startsWith('SFX/Chzzk_Signatures/');
        return !existing
            || existing.bytes !== stat.size
            || existing.mtimeMs !== Math.round(stat.mtimeMs)
            || (isChatVoice && existing.policyVersion !== CHAT_VOICE_POLICY_VERSION);
    });

    let cursor = 0;
    let completed = 0;
    let failed = 0;
    console.log(`[audio-levels] ${files.length} files found; ${pending.length} require analysis.`);

    async function worker() {
        while (cursor < pending.length) {
            const filePath = pending[cursor++];
            try {
                const { relative, entry } = await analyze(filePath);
                entries[relative] = entry;
            } catch (error) {
                failed++;
                console.warn(`[audio-levels] skipped ${relativePath(filePath)}: ${error.message}`);
            }
            completed++;
            if (completed % 20 === 0 || completed === pending.length) {
                writeOutput(entries);
                console.log(`[audio-levels] ${completed}/${pending.length} analyzed (${failed} skipped).`);
            }
        }
    }

    await Promise.all(Array.from({ length: concurrency }, () => worker()));
    writeOutput(entries);
    console.log(`[audio-levels] wrote ${Object.keys(entries).length} profiles to ${relativePath(outputPath)}.`);
}

main().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
