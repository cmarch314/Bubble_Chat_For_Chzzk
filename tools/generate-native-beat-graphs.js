'use strict';

/** Regenerate the small reviewed native promotion set from candidate kits. */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const candidatePath = path.join(root, 'data', 'hunt', 'monster-kits', 'candidates', 'rathian.json');
const outputPath = path.join(root, 'js', 'effects', 'hunt', 'data', 'NativeMonsterBeatGraphs.generated.js');
const selectedIds = ['rathian.fireball', 'rathian.triple_fireball'];
const kit = JSON.parse(fs.readFileSync(candidatePath, 'utf8'));
const graphs = {};
for (const id of selectedIds) {
    const action = kit.actions.find(item => item.id === id);
    if (!action?.graph) throw new Error(`missing native candidate graph: ${id}`);
    const graph = JSON.parse(JSON.stringify(action.graph));
    graph.id = id;
    graph.actor = 'monster';
    graph.schemaVersion = 2;
    graph.backend = 'beat-v2';
    graph.reviewStatus = 'approved';
    if (id === 'rathian.fireball') {
        const launch = graph.beats.flatMap(beat => beat.events || [])
            .find(event => event.kind === 'projectile-launch');
        if (launch) launch.offsetTicks = 0;
    }
    graphs[id] = graph;
}
const source = `'use strict';\n\n/** Generated by tools/generate-native-beat-graphs.js. */\n` +
    `const HUNT_NATIVE_BEAT_GRAPHS = ${JSON.stringify({ rathian: graphs }, null, 4)};\n\n` +
    `if (typeof module !== 'undefined' && module.exports) module.exports = HUNT_NATIVE_BEAT_GRAPHS;\n` +
    `else globalThis.HUNT_NATIVE_BEAT_GRAPHS = HUNT_NATIVE_BEAT_GRAPHS;\n`;
if (process.argv.includes('--check')) {
    const current = fs.readFileSync(outputPath, 'utf8');
    process.stdout.write(current === source ? 'native BEAT graphs are up to date\n' : 'native BEAT graphs need regeneration\n');
    process.exitCode = current === source ? 0 : 1;
} else {
    fs.writeFileSync(outputPath, source, 'utf8');
    process.stdout.write(`generated ${outputPath}\n`);
}
